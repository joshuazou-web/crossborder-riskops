def current_language() -> str:
    """The active language, preferring the URL so a link carries it."""
    from_url = st.query_params.get("lang")
    if from_url in LANGUAGES:
        st.session_state["lang"] = from_url
    return st.session_state.get("lang", DEFAULT_LANGUAGE)


def t(text: str) -> str:
    """Translate, falling back to the English source text."""
    if current_language() == "zh":
        return ZH.get(text, text)
    return text


