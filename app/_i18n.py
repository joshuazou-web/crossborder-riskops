def translate_reason(text: str) -> str:
    """Render one engine reason string in the reader's language.

    Falls through to the original text rather than raising or blanking: a
    diagnostic the reader cannot understand is still better than a diagnostic
    that silently disappeared. `test_i18n.py` is what stops that fallthrough
    from becoming the normal case.
    """
    if not text or current_language() == "en":
        return text
    for pattern, replacement in _REASON_PATTERNS:
        translated, count = pattern.subn(replacement, text.strip())
        if count:
            return translated
    return text


def language_toggle() -> None:
    """The switch, top-right of the content area.

    Streamlit has no real top-right slot, so this is a narrow trailing column at
    the very top of the page. Placing it in the sidebar would have been easier
    and would have hidden it on the one screen where somebody most needs it: the
    first one they open.
    """
    spacer, control = st.columns([6, 1])
    with control:
        chosen = st.segmented_control(
            t("Language"),
            options=list(LANGUAGES),
            format_func=lambda code: LANGUAGES[code],
            default=current_language(),
            key="_language_control",
            label_visibility="collapsed",
        )
    if chosen and chosen != st.session_state.get("lang"):
        st.session_state["lang"] = chosen
        st.query_params["lang"] = chosen
        st.rerun()
    del spacer


def translation_coverage() -> dict[str, int]:
    """How much of the interface actually has a Chinese string.

    Exposed so a test can assert it rather than anyone guessing.
    """
    return {"translated": len(ZH), "language_count": len(LANGUAGES)}
